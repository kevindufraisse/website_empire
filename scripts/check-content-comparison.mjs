import assert from 'node:assert/strict'

export async function checkContentComparison(page) {
  await page.locator('#formula-secret[data-requested=false], #formula-secret[data-requested=true]').waitFor({ state: 'attached' })
  const section = page.locator('#home-comparison')
  assert.equal(await section.locator('input').count(), 0, 'Public offers replace invented calculator defaults')
  assert.equal(await section.locator('[data-comparison-price]').getAttribute('data-comparison-price'), '199')
  const basket = await section.locator('[data-comparison-basket]').innerText()
  assert(basket.includes('14 contenus originaux · 3 formats'))
  assert.equal(await section.locator('[data-comparison-basket] li').count(), 3)
  assert(basket.includes('vidéos courtes') && basket.includes('posts texte') && basket.includes('newsletters'))
  assert(basket.includes('ne comptent pas comme de nouveaux contenus'), 'Do not count cross-posting as new originals')
  const journey = section.locator('[data-comparison-journey]')
  assert.equal(await journey.locator('h3').count(), 4)
  assert((await journey.innerText()).includes('7 réseaux'))
  const formats = await section.locator('[data-comparison-formats]').innerText()
  for (const format of ['Clonage', 'Lead magnets', 'YouTube long']) assert(formats.includes(format))
  assert(formats.includes('ne sont pas ajoutés'), 'Special formats must not appear included in the costed basket')
  const money = section.locator('[data-comparison-axis=money]')
  assert((await money.locator('[data-comparison-cell=freelance]').innerText()).replace(/\s/g, '').includes('Dès1129€'))
  assert((await money.locator('[data-comparison-cell=freelance]').innerText()).includes('diffusion et suivi global à compléter'))
  assert((await money.locator('[data-comparison-cell=agency]').innerText()).includes('Offre plus large'), 'Agency volume is not claimed equivalent')
  assert((await money.locator('[data-comparison-cell=empire]').innerText()).replace(/\s/g, '').includes('1690crédits'))
  assert((await money.locator('[data-comparison-cell=empire]').innerText()).includes('597 €'))
  const time = section.locator('[data-comparison-axis=time]')
  assert((await time.locator('[data-comparison-cell=tools]').innerText()).includes('Ajouter newsletters'))
  assert((await time.locator('[data-comparison-cell=freelance]').innerText()).includes('8 posts seuls'), 'Text briefing time is not time for the whole basket')
  assert((await time.locator('[data-comparison-cell=empire]').innerText()).includes('Pas encore de moyenne chronométrée'))
  assert((await section.locator('[data-comparison-success]').innerText()).includes('Pas de taux de continuité mesuré'))
  assert((await section.locator('[data-comparison-performance]').innerText()).includes('42 contenus originaux'))
  const urls = await section.locator('a[target=_blank]').evaluateAll(nodes => nodes.map(a => a.href))
  for (const url of ['https://clement-aouadene.fr/', 'https://studio.clicnstart.com/', 'https://www.webplume.net/tarifs/', 'https://flowify.fr/tarifs/']) assert(urls.includes(url), `Missing primary offer source: ${url}`)
  await section.getByRole('link', { name: 'Voir le calcul' }).first().focus()
  await page.keyboard.press('Enter')
  const details = section.locator('#comparison-method')
  assert(await details.evaluate(el => el.open), 'Calculation link must open the details')
  const calculation = (await details.innerText()).replace(/\s/g, '')
  assert(calculation.includes('600+289+2×120=1129'))
  assert(calculation.includes('8posts×85crédits+4Reelsstandard×195+2newsletters×115=1690crédits'))
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), 'Sources must not overflow horizontally')
  await details.locator('summary').focus()
  await page.keyboard.press('Enter')
  assert(!(await details.evaluate(el => el.open)), 'Sources can be collapsed by keyboard')
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), 'Comparison must not overflow horizontally')
}
