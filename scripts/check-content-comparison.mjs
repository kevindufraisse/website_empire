import assert from 'node:assert/strict'

export async function checkContentComparison(page) {
  await page.locator('#formula-secret[data-requested=false], #formula-secret[data-requested=true]').waitFor({ state: 'attached' })
  const section = page.locator('#home-comparison')
  const budget = section.locator('#comparison-budget-tools')
  const hours = section.locator('#comparison-hours-tools')
  const empireHours = section.locator('#comparison-hours-empire')
  const alternative = section.locator('#comparison-alternative')
  const expect = async (attribute, expected, message) => {
    await page.waitForFunction(({ attribute, expected }) => document.querySelector(`#home-comparison [${attribute}]`)?.getAttribute(attribute) === expected, { attribute, expected }, { timeout: 5000 })
    assert.equal(await section.locator(`[${attribute}]`).getAttribute(attribute), expected, message)
  }
  assert.equal(await section.locator('[data-comparison-price]').getAttribute('data-comparison-price'), '199')
  assert((await section.locator('#comparison-assumptions').innerText()).includes('exemples modifiables'))
  await budget.fill('250.5')
  await expect('data-budget-delta', '-51.5', 'Preserve cents and allow the alternative to cost more')
  await hours.fill('2')
  await expect('data-hours-delta', '-2', 'Empire can require more personal time in the simulation')
  assert((await section.locator('[data-hours-delta]').innerText()).includes('en plus'))
  await empireHours.fill('1.5')
  await expect('data-hours-delta', '0.5', 'Empire time must also be editable')
  await budget.fill('199.1')
  await expect('data-budget-delta', '-0.1', 'Avoid floating-point residue in currency differences')
  await budget.fill('199')
  await expect('data-budget-delta', '0', 'Equal budgets show no saving')
  await budget.fill('')
  await expect('data-budget-delta', '', 'An empty estimate is not a zero-cost alternative')
  await budget.fill('-1')
  assert.equal(await budget.getAttribute('aria-invalid'), 'true')
  await expect('data-budget-delta', '')
  await budget.fill('60000')
  await expect('data-budget-delta', '', 'Out-of-range estimates must not create a saving')
  await budget.fill('0')
  await expect('data-budget-delta', '199', 'A genuinely free tool setup is supported')
  await hours.fill('')
  await expect('data-hours-delta', '')
  await hours.fill('0')
  await empireHours.fill('0')
  await expect('data-hours-delta', '0')
  await alternative.selectOption('2')
  await expect('data-budget-delta', '-1601')
  await expect('data-hours-delta', '4')
  await section.getByRole('button', { name: 'Rétablir l’exemple' }).click()
  await alternative.selectOption('0')
  assert.equal(await budget.inputValue(), '80')
  await expect('data-budget-delta', '119')
  await expect('data-hours-delta', '12')
  assert(!(await section.innerText()).includes('NaN'))
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), 'Comparison must not overflow horizontally')
}
